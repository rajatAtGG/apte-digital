// Assemble the deployable PWA in dist/:
//   app/ (sources) + vendored sqlite-wasm + gzipped database with a content
//   hash in its name + generated js/config.js + service worker file lists.
// Run after `make build` (needs build/apte.sqlite) and `npm install`.

import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { gzipSync } from 'node:zlib';

const ROOT = new URL('..', import.meta.url).pathname;
const DIST = join(ROOT, 'dist');
const DB = join(ROOT, 'build', 'apte.sqlite');
const SQLITE = join(ROOT, 'node_modules', '@sqlite.org', 'sqlite-wasm', 'dist');

if (!existsSync(DB)) throw new Error('build/apte.sqlite is missing: run `make build` first');
if (!existsSync(SQLITE)) throw new Error('sqlite-wasm is missing: run `npm install` first');

rmSync(DIST, { recursive: true, force: true });
cpSync(join(ROOT, 'app'), DIST, { recursive: true });

// SQLite WebAssembly build (ES module + wasm, loaded relative to each other).
mkdirSync(join(DIST, 'vendor', 'sqlite3'), { recursive: true });
for (const f of ['index.mjs', 'sqlite3.wasm']) cpSync(join(SQLITE, f), join(DIST, 'vendor', 'sqlite3', f));
writeFileSync(join(DIST, 'vendor', 'sqlite3', 'NOTICE.txt'),
  'SQLite is in the public domain. The @sqlite.org/sqlite-wasm wrapper is Apache-2.0 licensed.\n');

// Database: gzip it and put its hash in the name so caches never go stale.
const raw = readFileSync(DB);
const dataHash = createHash('sha256').update(raw).digest('hex').slice(0, 12);
const gz = gzipSync(raw, { level: 9 });
const dbName = `data/apte.${dataHash}.sqlite.gz`;
mkdirSync(join(DIST, 'data'), { recursive: true });
writeFileSync(join(DIST, dbName), gz);

const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : [p];
});

// App version = hash of every shell file (config.js and sw.js excluded,
// since they are generated from it).
const shell = walk(DIST).map((p) => relative(DIST, p))
  .filter((p) => !p.startsWith('data/') && p !== 'sw.js' && !p.endsWith('.txt'))
  .sort();
const h = createHash('sha256');
for (const f of shell) if (f !== 'js/config.js') h.update(f).update(readFileSync(join(DIST, f)));
const appVersion = h.update(dataHash).digest('hex').slice(0, 12);

writeFileSync(join(DIST, 'js', 'config.js'),
  `// Generated by scripts/build-app.mjs\nexport const DB_URL = '${dbName}';\n`
  + `export const DB_GZ_BYTES = ${gz.length};\nexport const APP_VERSION = '${appVersion}';\n`);

const shellFiles = ['./', ...shell];
const sw = readFileSync(join(DIST, 'sw.js'), 'utf8')
  .replace('__APP_VERSION__', appVersion)
  .replace('__DATA_VERSION__', dataHash)
  .replace('__SHELL_FILES__', JSON.stringify(shellFiles))
  .replace('__DATA_FILES__', JSON.stringify([dbName]));
writeFileSync(join(DIST, 'sw.js'), sw);
writeFileSync(join(DIST, '.nojekyll'), '');

const mb = (n) => `${(n / 1e6).toFixed(1)} MB`;
console.log(`dist/ ready: app ${appVersion}, ${shell.length} shell files, ${dbName} (${mb(gz.length)}, ${mb(raw.length)} unpacked)`);
